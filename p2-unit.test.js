'use strict';
const test=require('node:test');const assert=require('node:assert/strict');
const {automaticDiscount}=require('../src/domain/discount');
const {shippingCost}=require('../src/domain/shipping');
const {validateQuantity}=require('../src/domain/quantity');
const {percentOf}=require('../src/domain/money');
const {evaluateCoupon}=require('../src/domain/coupon');
const {quoteLines}=require('../src/domain/pricing');
const {normalizeAddress}=require('../src/domain/address');
const {setClock,resetClock}=require('../src/domain/clock');
const {totalsForOrder}=require('../src/domain/orderTotals');
const line=(price,quantity=1)=>[{productId:'p',name:'Item',unitPrice:price,quantity}];
test('CT-U01 / RN-01 equivalência: R$199,99 não recebe desconto',()=>assert.equal(automaticDiscount(199.99),0));
test('CT-U02 / RN-01 limite: R$200,00 recebe R$20',()=>assert.equal(automaticDiscount(200),20));
test('CT-U03 / RN-01 acima do limite: R$200,01',()=>assert.equal(automaticDiscount(200.01),20));
test('CT-U04 / RN-02 frete: R$299,99 custa R$18,50',()=>assert.equal(shippingCost(299.99),18.5));
test('CT-U05 / RN-02 frete: R$300,00 gratuito',()=>assert.equal(shippingCost(300),0));
test('CT-U06 / RN-03 equivalência inválida negativa',()=>assert.equal(validateQuantity(-1).ok,false));
test('CT-U07 / RN-03 valor-limite zero',()=>assert.equal(validateQuantity(0).ok,false));
test('CT-U08 / RN-03 valor-limite inteiro mínimo 1',()=>assert.equal(validateQuantity(1).ok,true));
test('CT-U09 / RN-06 arredondamento monetário meio centavo half-up',()=>assert.equal(percentOf(200.05,10),20.01));
test('CT-U10 / RN-04 cupom vencido rejeitado',()=>{setClock('2026-10-07T15:00:00Z');try{assert.equal(evaluateCoupon({active:true,type:'percent',value:20,expiresAt:'2026-10-06'}).ok,false)}finally{resetClock()}});
test('CT-U11 / RN-04 cupom válido até fim do dia',()=>{setClock('2026-10-07T23:59:59Z');try{assert.equal(evaluateCoupon({active:true,type:'percent',value:20,expiresAt:'2026-10-07'}).ok,true)}finally{resetClock()}});
test('CT-U12 / RN-05 maior desconto, não cumulativo',()=>{const q=quoteLines({lines:line(250),coupon:{active:true,code:'X',type:'fixed',value:30,expiresAt:'2027-12-31'}});assert.equal(q.ok,true);assert.equal(q.discount,30);assert.equal(q.total,238.5)});
test('CT-U13 / RN-06 total do pedido desconta benefício',()=>assert.equal(totalsForOrder({subtotal:300,discount:30,shipping:0}).total,270));
test('CT-U14 / RN-13 endereço incompleto é recusado',()=>assert.equal(normalizeAddress({street:'Rua ABC'}).ok,false));
test('CT-U15 / RN-06 cotação R$300 frete zero',()=>{const q=quoteLines({lines:line(150,2)});assert.equal(q.ok,true);assert.deepEqual([q.subtotal,q.discount,q.shipping,q.total],[300,30,0,270])});
